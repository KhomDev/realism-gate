//! Derives the shipped severity table from `data/measured.json` at build
//! time, by the severity floor in `src/rules/measured/floor.rs`.
//!
//! The output, `$OUT_DIR/derived_severity.rs`, is one row per rule and
//! language cell in the data file: the level the floor allows. A cell that is
//! not measured, or not marked `"fresh": true`, derives `note`. Replacing the
//! cells (for example with P2R-2 FINAL cells) is a data change: the next build
//! re-derives the table, and nothing here or in the catalog is edited.

use std::fmt::Write as _;
use std::path::PathBuf;

#[path = "src/rules/measured/floor.rs"]
#[allow(dead_code)]
mod floor;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let data = manifest.join("data/measured.json");
    println!("cargo:rerun-if-changed=data/measured.json");
    println!("cargo:rerun-if-changed=src/rules/measured/floor.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let text = std::fs::read_to_string(&data).expect("data/measured.json is readable");
    let doc: serde_json::Value = serde_json::from_str(&text).expect("data/measured.json is JSON");
    let rules = doc
        .get("rules")
        .and_then(serde_json::Value::as_object)
        .expect("data/measured.json has a `rules` object");

    let mut out = String::new();
    out.push_str("// Generated by crates/rg-rules/build.rs from data/measured.json. Do not edit.\n");
    out.push_str("/// (rule, language, level) for every cell: 0 = note, 1 = warn, 2 = error.\n");
    out.push_str("pub(crate) static DERIVED: &[(&str, &str, u8)] = &[\n");
    for (rule, cells) in rules {
        let cells = cells
            .as_object()
            .unwrap_or_else(|| panic!("{rule}: cells must be an object"));
        for (lang, cell) in cells {
            let measured = cell.get("status").and_then(serde_json::Value::as_str) == Some("measured");
            let fresh = cell
                .get("fresh")
                .and_then(serde_json::Value::as_bool)
                .unwrap_or(false);
            let count = |key: &str| -> u32 {
                cell.get(key)
                    .and_then(serde_json::Value::as_u64)
                    .map(|v| u32::try_from(v).expect("count fits in u32"))
                    .unwrap_or(0)
            };
            let level = floor::level(measured, fresh, count("tp"), count("fp"));
            writeln!(out, "    ({rule:?}, {lang:?}, {level}),").expect("write to String");
        }
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("derived_severity.rs");
    std::fs::write(dest, out).expect("write derived_severity.rs");
}
